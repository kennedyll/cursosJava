package aula03_condicionais;

public class Comparacoes {
    public static void main(String[] args) {
        
        int x = 5;
        System.out.println(x == 5);
        System.out.println(x != 5);
        System.out.println(x > 3 && x < 10);
        System.out.println(x < 3 || x == 5);
        System.out.println(!(x == 5));

    }
    
}
